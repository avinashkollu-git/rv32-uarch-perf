#!/usr/bin/env python3
"""Writes the two benchmarks that are tedious by hand (run once; output is committed).

big_loop.asm      : a 96-instruction loop body (384 bytes of code) run 8 times.
                    Fits a 512-byte I-cache, thrashes the smaller ones (capacity).
call_conflict.asm : two small functions exactly 256 bytes apart, called in turn.
                    They map to the same line in any direct-mapped cache of
                    <= 256 bytes (conflict misses), not in 512 bytes.
"""
import os
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "bench")

ops = ["add", "xor", "sub", "or", "and", "sll", "srl"]
body = [f"        {ops[i % 7]}   x{1 + i % 8}, x{1 + (i + 3) % 8}, x{1 + (i + 5) % 8}" for i in range(96)]
big = ["# Generated by tools/gen_bench.py: 96-instruction body (384 B of code), 8 iterations.",
       "# Fits a 512 B I-cache, but not 256 B or less: capacity misses every iteration.",
       *[f"        li    x{r}, {r * 7}" for r in range(1, 9)],
       "        li    x20, 8",
       "loop:", *body,
       "        addi  x20, x20, -1",
       "        bne   x20, x0, loop",
       "        sw    x1, 0(x0)",
       "halt:   j     halt"]
open(os.path.join(here, "big_loop.asm"), "w").write("\n".join(big) + "\n")

def pad_to(lines, byte_addr):
    # instruction lines are indented; labels sit alone on their own line
    n = sum(1 for l in lines if l.startswith("        "))
    return lines + ["        nop"] * (byte_addr // 4 - n)

def func(name, k):
    return [f"{name}:", *[f"        addi  x5, x5, {k + i}" for i in range(7)], "        jalr  x0, ra, 0"]

cc = ["# Generated by tools/gen_bench.py: fa at 0x140 and fb at 0x240 (256 B apart)",
      "# share a cache index for any direct-mapped I-cache of <= 256 B: conflict misses.",
      "        li    x20, 20",
      "        li    x5, 0",
      "loop:",
      "        jal   ra, fa",
      "        jal   ra, fb",
      "        addi  x20, x20, -1",
      "        bne   x20, x0, loop",
      "        sw    x5, 0(x0)",
      "halt:",
      "        j     halt"]
cc = pad_to(cc, 0x140) + func("fa", 1)
cc = pad_to(cc, 0x240) + func("fb", 100)
open(os.path.join(here, "call_conflict.asm"), "w").write("\n".join(cc) + "\n")
