#!/usr/bin/perl
# perf_report.pl : turn the perf-study logs into a markdown summary.
#
#   perl scripts/perf_report.pl results/perf > results/perf/summary.md
#
# Reads <dir>/<cfg>/<bench>.log (written by scripts/perf_study.py). Each log
# has a CONFIG line, the RTL "PERF k=v ..." and "RESULT ..." lines, and the
# C++ model's "MODEL k=v ..." line. Writes:
#   1. IPC per benchmark vs I-cache size, predictor off and on (RTL counters)
#   2. cache and predictor rates, and the CPI stack, at one config
#   3. model-vs-RTL IPC error per benchmark and config
#   4. an ASCII plot of mean IPC vs I-cache size
use strict;
use warnings;

my $dir = shift or die "usage: $0 <results/perf>\n";
my $DETAIL = 'ic128_bp1';    # config used for the rates table

# %run{cfg}{bench} = { cfg info, rtl => {...}, model => {...}, pass => 0/1 }
my (%run, %benches);
for my $log (sort glob("$dir/*/*.log")) {
    my ($cfg, $bench) = $log =~ m{([^/]+)/([^/]+)\.log$} or next;
    open(my $fh, '<', $log) or die "$log: $!\n";
    my %r = (pass => 0);
    while (my $line = <$fh>) {
        my %kv = $line =~ /(\w+)=([\d.]+)/g;
        if    ($line =~ /^CONFIG /)      { @r{keys %kv} = values %kv }
        elsif ($line =~ /^PERF /)        { $r{rtl} = \%kv }
        elsif ($line =~ /^MODEL /)       { $r{model} = \%kv }
        elsif ($line =~ /^RESULT PASS/)  { $r{pass} = 1 }
    }
    close $fh;
    die "$log: RTL run did not pass\n" unless $r{pass} && $r{rtl} && $r{model};
    $run{$cfg}{$bench} = \%r;
    $benches{$bench} = 1;
}
die "no logs under $dir\n" unless %run;
my @benches = sort keys %benches;
my @sizes = sort { ($a || 1e9) <=> ($b || 1e9) } keys %{{ map { /^ic(\d+)_/ ? ($1 => 1) : () } keys %run }};
my $sizename = sub { $_[0] ? "$_[0] B" : "no cache (ideal)" };

sub ipc { my $p = shift; return $p->{cycles} ? $p->{instret} / $p->{cycles} : 0 }
sub pct { my ($a, $b) = @_; return $b ? sprintf('%.1f%%', 100 * $a / $b) : '-' }
sub geomean { my $s = 0; $s += log($_) for @_; return @_ ? exp($s / @_) : 0 }

# ---- 1. IPC tables ----
print "# Performance study (generated by scripts/perf_report.pl)\n\n";
my $lat = (values %{ (values %run)[0] })[0]{miss_lat};
print "Miss latency $lat cycles, 16-byte lines, BHT 64 entries, BTB 16 entries. ",
      "IPC = instret / cycles from the RTL counters. Mean = geometric mean.\n";
for my $bp (0, 1) {
    printf "\n## IPC, branch predictor %s\n\n", $bp ? 'ON' : 'OFF (predict not taken)';
    print '| Benchmark | ', join(' | ', map { $sizename->($_) } @sizes), " |\n";
    print '|---' x (@sizes + 1), "|\n";
    my %col;
    for my $b (@benches) {
        my @cells;
        for my $s (@sizes) {
            my $r = $run{"ic${s}_bp$bp"}{$b} or do { push @cells, '-'; next };
            my $v = ipc($r->{rtl});
            push @{ $col{$s} }, $v;
            push @cells, sprintf('%.3f', $v);
        }
        print "| $b | ", join(' | ', @cells), " |\n";
    }
    print '| **mean** | ', join(' | ', map { sprintf('**%.3f**', geomean(@{ $col{$_} || [] })) } @sizes), " |\n";
}

# ---- 2. rates and CPI stack ----
if ($run{$DETAIL}) {
    my $off = $DETAIL =~ s/_bp1$/_bp0/r;
    print "\n## Rates and CPI stack at $DETAIL (RTL counters)\n\n",
          "Miss rate = refills / fetches (wrong-path fetches included). MPKI = misses per 1000 retired.\n",
          "Mispredict rate = redirects / (branches + jumps). CPI = 1 + bubbles per instruction, by cause.\n\n",
          "| Benchmark | I\$ miss rate | I\$ MPKI | Mispredict (BP off) | Mispredict (BP on) | CPI | I\$ | load-use | branch | fill |\n",
          "|---|---|---|---|---|---|---|---|---|---|\n";
    for my $b (@benches) {
        my $p = $run{$DETAIL}{$b}{rtl};
        my $q = $run{$off}{$b} ? $run{$off}{$b}{rtl} : undef;
        my $ctrl = $p->{branches} + $p->{jumps};
        printf "| %s | %s | %.1f | %s | %s | %.3f | %.3f | %.3f | %.3f | %.3f |\n", $b,
            pct($p->{ic_miss}, $p->{ic_access}), 1000 * $p->{ic_miss} / $p->{instret},
            $q ? pct($q->{mispredicts}, $q->{branches} + $q->{jumps}) : '-',
            pct($p->{mispredicts}, $ctrl), $p->{cycles} / $p->{instret},
            map { $p->{$_} / $p->{instret} } qw(bub_ic bub_lu bub_br bub_fill);
    }
}

# ---- 3. model vs RTL ----
my @cfgs = sort { ($a =~ /ic(\d+)/)[0] <=> ($b =~ /ic(\d+)/)[0] or $a cmp $b } keys %run;
print "\n## C++ model vs RTL: IPC error (model - RTL) / RTL\n\n",
      '| Benchmark | ', join(' | ', @cfgs), " | mean abs |\n", '|---' x (@cfgs + 2), "|\n";
my @all;
for my $b (@benches) {
    my @e;
    for my $c (@cfgs) {
        my $r = $run{$c}{$b} or next;
        my $rtl = ipc($r->{rtl});
        push @e, 100 * (ipc($r->{model}) - $rtl) / $rtl;
    }
    my $mean = 0; $mean += abs($_) / @e for @e;
    push @all, @e;
    print "| $b | ", join(' | ', map { sprintf('%+.1f%%', $_) } @e), sprintf(" | %.1f%% |\n", $mean);
}
my $mean_all = 0; $mean_all += abs($_) / @all for @all;
my ($worst) = sort { abs($b) <=> abs($a) } @all;
printf "\nMean absolute IPC error over all %d runs: %.1f%%, worst %+.1f%%.\n", scalar @all, $mean_all, $worst;

# ---- 4. ASCII plot ----
print "\n## Mean IPC vs I-cache size (ASCII)\n\n```\n";
my $W = 50;
for my $s (@sizes) {
    for my $bp (0, 1) {
        my @v = map { ipc($run{"ic${s}_bp$bp"}{$_}{rtl}) } grep { $run{"ic${s}_bp$bp"}{$_} } @benches;
        my $g = geomean(@v);
        printf "%-8s BP %-3s |%-${W}s| %.3f\n", $s ? "$s B" : 'ideal', $bp ? 'on' : 'off',
            '#' x int($g * $W + 0.5), $g;
    }
}
print "                     0", ' ' x ($W - 4), "IPC 1.0\n```\n";
